import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { baseRecentUpdates } from '../assets/terminal/recent.base.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const recentOutput = path.join(root, 'assets', 'terminal', 'recent.generated.js');
const essaysOutput = path.join(root, 'assets', 'terminal', 'essays.generated.js');
const autoUpdateAfter = Math.floor(new Date('2026-10-29T16:30:00+08:00').getTime() / 1000);
const extensions = new Set(['.html', '.pdf', '.md', '.pptx']);
const excludedDirectories = new Set(['.git', '.github', 'node_modules', 'dist', 'assets', 'scripts', 'src']);
const ignoredFiles = new Set([
  'index.html',
  'classic.html',
  'terminal.html',
  'replace_html.html',
  'gem5_temp.html',
  'pim_temp.html',
  'trivial_temp.html',
  'leetcodetemp.html',
  'to_be_updated.html',
  'to_be_read.html',
]);

function walk(directory) {
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const absolute = path.join(directory, entry.name);
    const relative = path.relative(root, absolute);
    if (entry.isDirectory()) {
      if (!excludedDirectories.has(relative)) files.push(...walk(absolute));
      continue;
    }
    if (!entry.isFile()) continue;
    if (ignoredFiles.has(relative) || /^README(?:\.|$)/i.test(entry.name)) continue;
    if (extensions.has(path.extname(entry.name).toLowerCase())) files.push(relative.split(path.sep).join('/'));
  }
  return files;
}

function getCommitTimes() {
  const times = new Map();
  try {
    const log = execFileSync('git', [
      '-c', 'core.quotepath=false',
      'log', '--pretty=format:COMMIT%x09%ct', '--name-only', '--', '.',
    ], { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
    let timestamp = 0;
    for (const line of log.split(/\r?\n/)) {
      if (line.startsWith('COMMIT\t')) {
        timestamp = Number(line.slice(7)) || 0;
      } else if (line && !times.has(line)) {
        times.set(line, timestamp);
      }
    }
  } catch {
    // Filesystem timestamps remain a fallback outside a Git checkout.
  }
  return times;
}

function labelFor(relative) {
  const basename = path.posix.basename(relative, path.posix.extname(relative));
  const label = basename.replace(/_+/g, ' ').trim();
  return label.replace(/[&<>]/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' })[character]);
}

async function importManifest(output, exportName) {
  try {
    const module = await import(`${pathToFileURL(output).href}?reload=${Date.now()}`);
    return module[exportName] || [];
  } catch {
    return [];
  }
}

const previousRecent = await importManifest(recentOutput, 'recentUpdates');
const previousEssays = await importManifest(essaysOutput, 'essayEntries');
const previousLabels = new Map([...previousRecent, ...previousEssays].map(([href, label]) => [href, label]));
const commitTimes = getCommitTimes();

let candidates = walk(root);
const candidateSet = new Set(candidates);
candidates = candidates.filter((relative) => {
  if (path.posix.extname(relative).toLowerCase() !== '.md') return true;
  return !candidateSet.has(`${relative.slice(0, -3)}.html`);
});

const datedCandidates = candidates.map((relative) => {
  const href = `./${relative}`;
  const committed = commitTimes.get(relative);
  const timestamp = committed ?? fs.statSync(path.join(root, relative)).mtimeMs / 1000;
  return { href, relative, timestamp };
});
const byNewest = (a, b) => b.timestamp - a.timestamp || a.relative.localeCompare(b.relative);
const baseHrefs = new Set(baseRecentUpdates.map(([href]) => href));

const newRecent = datedCandidates
  .filter(({ href, timestamp }) => timestamp >= autoUpdateAfter && !baseHrefs.has(href))
  .sort(byNewest)
  .map(({ href }) => [href, previousLabels.get(href) || labelFor(href)]);
const recentEntries = [...newRecent, ...baseRecentUpdates].slice(0, 40);

const essayEntries = datedCandidates
  .filter(({ relative }) => relative.startsWith('essays/'))
  .sort(byNewest)
  .map(({ href }) => [href, previousLabels.get(href) || labelFor(href)]);

function writeManifest(output, exportName, entries) {
  const source = `// Generated by scripts/generate-recent.mjs. Existing labels are preserved on rebuild.\nexport const ${exportName} = ${JSON.stringify(entries, null, 2)};\n`;
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== source) fs.writeFileSync(output, source);
}

writeManifest(recentOutput, 'recentUpdates', recentEntries);
writeManifest(essaysOutput, 'essayEntries', essayEntries);
console.log(`Recent manifest: ${recentEntries.length} items (${newRecent.length} new); Essays: ${essayEntries.length}`);
